-- Pure client modules: panel contract values, placement preview snapping,
-- input safety and the Build drawer state machine.
return function(T, H)
	local PanelTheme = H.load("src/client/UI/PanelTheme")
	local PlacementPreview = H.load("src/client/Build/PlacementPreview")
	local BuildInput = H.load("src/client/Build/BuildInput")
	local BuildSession = H.load("src/client/Build/BuildSession")
	local Config = H.load("src/shared/Config")

	-- PanelTheme ------------------------------------------------------------

	T.test("theme tokens match docs/ui-contract.md exactly", function()
		local C = PanelTheme.Colors
		T.deepEq(C.bg, { 16, 24, 29 })
		T.deepEq(C.card, { 31, 43, 49 })
		T.deepEq(C.teal, { 91, 224, 198 })
		T.deepEq(C.white, { 237, 235, 225 })
		T.deepEq(C.muted, { 155, 175, 180 })
		T.deepEq(C.stroke, { 66, 89, 94 })
		T.eq(PanelTheme.FontName, "GothamMedium")
		T.eq(PanelTheme.TextSize.button, 12)
		T.eq(PanelTheme.TextSize.heading, 13)
		T.eq(PanelTheme.TextSize.description, 10)
		T.eq(PanelTheme.TextSize.title, 17)
		T.eq(PanelTheme.TextSize.status, 11)
		T.eq(PanelTheme.TextSize.handle, 9)
		T.eq(PanelTheme.ButtonRadius, 8)
		T.eq(PanelTheme.Drawer.radius, 14)
		T.eq(PanelTheme.Drawer.transparency, 0.015)
		T.eq(PanelTheme.Drawer.strokeTransparency, 0.25)
		local L = PanelTheme.Layout
		T.eq(L.tabsX .. "," .. L.tabsY .. "," .. L.tabsHeight .. "," .. L.tabsGap, "14,72,34,6")
		T.eq(L.bodyX .. "," .. L.bodyY .. "," .. L.bodyWidthInset .. "," .. L.bodyHeightInset, "14,119,28,177")
		T.eq(L.footerX .. "," .. L.footerBottomInset .. "," .. L.footerHeight, "18,49,38")
		T.eq(L.closeSize .. "," .. L.closeRightInset .. "," .. L.closeTop, "30,48,12")
		T.eq(L.handleText, "DRAG TO MOVE")
		T.eq(PanelTheme.ScreenGui.DisplayOrder, 20)
		T.eq(PanelTheme.ScreenGui.ResetOnSpawn, false)
		T.eq(PanelTheme.ScreenGui.IgnoreGuiInset, false)
	end)

	T.test("responsive fit follows the live formula", function()
		local big = PanelTheme.fit(1920, 1080)
		T.eq(big.width, 402)
		T.eq(big.y, 178)
		T.eq(big.height, 710)
		T.eq(big.x, 18)
		local short = PanelTheme.fit(800, 500)
		T.eq(short.y, 108)
		T.eq(short.height, 368)
		local phone = PanelTheme.fit(390, 300)
		T.eq(phone.width, 366)
		T.eq(phone.height, 230, "minimum height 230")
	end)

	T.test("dragging is clamped on-screen", function()
		local x, y = PanelTheme.clamp(-50, 9000, 402, 600, 1280, 720)
		T.eq(x, 0)
		T.eq(y, 120)
		x, y = PanelTheme.clamp(300, 50, 402, 600, 1280, 720)
		T.eq(x, 300)
		T.eq(y, 50)
		x, y = PanelTheme.clamp(10, 10, 500, 900, 400, 300)
		T.eq(x, 0, "panel larger than viewport pins to 0")
		T.eq(y, 0)
	end)

	T.test("five filters fit one row at panel width", function()
		local width = PanelTheme.rowButtonWidth(5, 402 - 28)
		T.ok(width >= 65, "each filter button stays readable: " .. width)
	end)

	-- PlacementPreview ------------------------------------------------------

	local BOUNDS = { halfX = 20, halfZ = 15, height = 16 }
	local PLANT = { 2.93, 5.72, 2.93 }
	local function preview(hit, snap, yaw, size)
		return PlacementPreview.compute(hit, { size = size or PLANT, yaw = yaw or 0, bounds = BOUNDS, snap = snap ~= false, config = Config })
	end

	T.test("snaps onto the floor and onto furniture tops", function()
		local floor = preview({ x = 2.4, y = -0.02, z = -3.6, upDot = 1 })
		T.eq(floor.valid, true)
		T.eq(floor.transform.x, 2)
		T.eq(floor.transform.z, -4)
		T.eq(floor.transform.y, 0, "tiny negative floor height clamps to 0")
		local tabletop = preview({ x = 0.2, y = 1.75, z = 0.1, upDot = 0.99 })
		T.eq(tabletop.valid, true)
		T.eq(tabletop.transform.y, 1.75, "rests on the coffee table top")
	end)

	T.test("grid snapping can be turned off", function()
		local p = preview({ x = 2.37, y = 0, z = -3.61, upDot = 1 }, false)
		T.eq(p.valid, true)
		T.ok(math.abs(p.transform.x - 2.37) < 1e-9)
	end)

	T.test("walls, undersides and empty space are not surfaces", function()
		T.eq(preview({ x = 0, y = 3, z = 0, upDot = 0.2 }).code, "NoSurface")
		T.eq(preview({ x = 0, y = 3, z = 0, upDot = -1 }).code, "NoSurface")
		T.eq(preview(nil).code, "NoSurface")
	end)

	T.test("preview turns invalid exactly where the server would reject", function()
		local shelf = { 6.22, 12.14, 1.59 }
		local out = preview({ x = 17, y = 0, z = 0, upDot = 1 }, true, 0, shelf)
		T.eq(out.valid, false)
		T.eq(out.code, "OutOfBounds")
		T.ok(out.transform ~= nil, "still drawable as an invalid ghost")
		T.eq(preview({ x = 19, y = 0, z = 0, upDot = 1 }, true, 90, shelf).valid, true)
		T.eq(preview({ x = 0, y = 12, z = 0, upDot = 1 }).code, "OutOfBounds", "too tall on a high shelf")
	end)

	-- BuildInput ------------------------------------------------------------

	local function classify(keyCode, inputType, gameProcessed, textFocused)
		return BuildInput.classify({ keyCode = keyCode, inputType = inputType or "Keyboard", gameProcessed = gameProcessed == true, textFocused = textFocused == true })
	end

	T.test("text entry is always safe", function()
		T.eq(classify("R", "Keyboard", false, true), nil)
		T.eq(classify("Escape", "Keyboard", true, true), nil)
		T.eq(classify(nil, "MouseButton1", false, true), nil)
	end)

	T.test("Escape cancels even when processed; R and clicks only when unprocessed", function()
		T.eq(classify("Escape", "Keyboard", true), "cancel")
		T.eq(classify("R"), "rotate")
		T.eq(classify("R", "Keyboard", true), nil)
		T.eq(classify(nil, "MouseButton1"), "pointer")
		T.eq(classify(nil, "Touch"), "pointer")
		T.eq(classify(nil, "MouseButton1", true), nil, "clicks on UI never place")
	end)

	T.test("free-camera and host keys are never handled by the builder", function()
		for _, key in ipairs({ "E", "Q", "One", "Two", "Three", "Four", "Five", "V", "F" }) do
			T.eq(classify(key), nil, key)
		end
		T.eq(classify(nil, "MouseButton2"), nil, "right mouse stays with PodcastCamera")
	end)

	-- BuildSession ----------------------------------------------------------

	local function session(isHost)
		local s = BuildSession.new(Config)
		s:opened(isHost ~= false)
		return s
	end

	T.test("choose, rotate preview, cancel", function()
		local s = session()
		T.eq(s:choose("cozy_plant_01", true), true)
		T.eq(s.mode, "placing")
		T.eq(s:rotate(), "preview")
		T.eq(s.previewYaw, 15)
		for _ = 1, 23 do
			s:rotate()
		end
		T.eq(s.previewYaw, 0, "wraps at 360")
		s:cancel()
		T.eq(s.mode, "idle")
	end)

	T.test("not-installed items and read-only hosts cannot start placing", function()
		local s = session()
		T.eq(s:choose("retro_tv_cart_01", false), false)
		T.eq(s.mode, "idle")
		local guest = session(false)
		T.eq(guest.readOnly, true)
		T.eq(guest:choose("cozy_plant_01", true), false)
		T.eq(guest.message, "Only the host can build.")
	end)

	T.test("select, move preview, escape back to selection, rotate request", function()
		local s = session()
		s:select("i3")
		T.eq(s.mode, "selected")
		T.eq(s:rotate(), "request", "rotating a selected item asks the server")
		T.eq(s:beginMove("cozy_plant_01", 45), true)
		T.eq(s.previewYaw, 45)
		s:cancel()
		T.eq(s.mode, "selected")
		T.eq(s.selectedId, "i3")
		s:cancel()
		T.eq(s.mode, "idle")
	end)

	T.test("responses: success selects, failure keeps the preview, status updates undo/redo", function()
		local s = session()
		s:choose("cozy_plant_01", true)
		s:applyResponse("Place", { ok = false, code = "OutOfBounds", status = { state = "ready", canUndo = false, canRedo = false, revision = 0 } })
		T.eq(s.mode, "placing", "rejected placement keeps the preview")
		s:applyResponse("Place", { ok = true, id = "i1", status = { state = "ready", canUndo = true, canRedo = false, revision = 1 } })
		T.eq(s.mode, "selected")
		T.eq(s.selectedId, "i1")
		T.eq(s.canUndo, true)
		T.eq(s.revision, 1)
		s:applyResponse("Undo", { ok = true, id = "i1", status = { state = "ready", canUndo = false, canRedo = true, revision = 2 } })
		T.eq(s.mode, "idle")
		T.eq(s.canRedo, true)
	end)

	T.test("RecoveryNeeded visibly pauses edits until the server is ready again", function()
		local s = session()
		s:applyResponse("Place", { ok = false, code = "AuthorityLost", recoveryNeeded = true, status = { state = "recovery", revision = 0 } })
		T.eq(s.paused, true)
		T.eq(s:canEdit(), false)
		T.ok(s.message and s.message:find("paused"), "visible message")
		T.eq(s:choose("cozy_plant_01", true), false)
		s:applyResponse("Status", { ok = true, status = { state = "recovery", revision = 0 } })
		T.eq(s.paused, true)
		s:applyResponse("Status", { ok = true, status = { state = "ready", revision = 0 } })
		T.eq(s.paused, false)
		T.eq(s.message, nil)
		T.eq(s:canEdit(), true)
	end)

	T.test("host loss, room switch and respawn cancel previews and request exit", function()
		local s = session()
		s:choose("cozy_plant_01", true)
		T.eq(s:hostChanged(true), false, "still host: nothing to do")
		T.eq(s:hostChanged(false), true)
		T.eq(s.mode, "idle")
		T.eq(s.readOnly, true)
		local r = session()
		r:select("i1")
		r:beginMove("cozy_plant_01", 0)
		T.eq(r:roomSwitched(), true)
		T.eq(r.mode, "selected", "move cancelled")
		local p = session()
		p:choose("cozy_plant_01", true)
		T.eq(p:respawned(), true)
		T.eq(p.mode, "idle")
	end)

	T.test("becoming host while the drawer is open lifts read-only", function()
		local s = session(false)
		T.eq(s:canEdit(), false)
		T.eq(s:hostChanged(true), false)
		T.eq(s.readOnly, false)
		T.eq(s:canEdit(), true)
	end)

	T.test("an unexpected BuildRevision cancels an in-progress move", function()
		local s = session()
		s:applyResponse("Status", { ok = true, status = { state = "ready", revision = 4 } })
		s:select("i1")
		s:beginMove("cozy_plant_01", 0)
		s:revisionChanged(4)
		T.eq(s.mode, "moving", "our own revision is not a surprise")
		s:revisionChanged(5)
		T.eq(s.mode, "selected")
		T.ok(s.message:find("move cancelled"))
	end)

	T.test("filters: the five collections only", function()
		local s = session()
		for _, id in ipairs({ "cozy", "1980s", "retro", "winter", "futuristic" }) do
			T.eq(s:setFilter(id), true, id)
		end
		T.eq(s:setFilter("vaporwave"), false)
		T.eq(s.filter, "futuristic")
	end)

	T.test("NotHost response flips the session to read-only and drops the preview", function()
		local s = session()
		s:choose("cozy_plant_01", true)
		s:applyResponse("Place", { ok = false, code = "NotHost", status = { state = "ready", revision = 0 } })
		T.eq(s.readOnly, true)
		T.eq(s.mode, "idle")
	end)
end
